"""Regenerate program/TODO.md from program/rooms.json: the rooms flagged for later, the rooms
labelled but still missing an access or operation, and a per-level summary. The owner confirms
rooms by number in chat; this list is what is still open. Run: python -I scripts/program_todo.py
"""
import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAM = os.path.join(ROOT, "program")
LEVEL_ORDER = ["Basement", "Level 1", "Level 2", "Level 3", "Level 4"]


def main():
    path = os.path.join(PROGRAM, "rooms.json")
    if not os.path.exists(path):
        print("no program/rooms.json")
        return 1
    with open(path, encoding="utf-8") as f:
        program = json.load(f)
    rooms = program.get("rooms", {})

    def level_key(item):
        lv = item[1].get("level", "")
        return (LEVEL_ORDER.index(lv) if lv in LEVEL_ORDER else 99, int(str(item[1].get("number", "0")) or 0))

    items = sorted(rooms.items(), key=level_key)
    flagged = [(i, r) for i, r in items if r.get("status") == "flagged"]
    done = [(i, r) for i, r in items if r.get("status") == "done"]
    no_access = [(i, r) for i, r in done if not r.get("access")]
    no_hours = [(i, r) for i, r in done if not r.get("hours")]
    inferred = [(i, r) for i, r in done if r.get("access_inferred")]

    out = ["# Program: what is still open", "",
           "Regenerated by scripts/program_todo.py from program/rooms.json (%s). Confirm rooms by number in chat." % program.get("meta", {}).get("updated", "?"),
           "", "%d rooms labelled, %d flagged for later, %d labelled without an access rule, %d without an operation, %d with an access rule inferred from a general remark." % (
               len(done), len(flagged), len(no_access), len(no_hours), len(inferred)), ""]
    out.append("## Flagged for later")
    out.append("")
    if not flagged:
        out.append("Nothing flagged.")
    for i, r in flagged:
        out.append("- [ ] %s, room %s (id %s, %s m2): %s" % (r.get("level"), r.get("number"), i, r.get("area_m2"), r.get("flag_reason") or "decide later"))
    out += ["", "## Labelled, access not yet stated", ""]
    if not no_access:
        out.append("None.")
    for i, r in no_access:
        out.append("- [ ] %s, room %s (id %s): %s%s" % (r.get("level"), r.get("number"), i, r.get("use") or "?", (", " + r["name"]) if r.get("name") else ""))
    out += ["", "## Access inferred from a general remark (confirm or correct)", ""]
    if not inferred:
        out.append("None.")
    for i, r in inferred:
        out.append("- [ ] %s, room %s (id %s): %s, access %s: %s" % (r.get("level"), r.get("number"), i, r.get("use") or "?", r.get("access"), r.get("access_inferred")))
    out += ["", "## Labelled, operation (business hours or 24/7) not yet stated", ""]
    if not no_hours:
        out.append("None.")
    out.append("%s" % ", ".join("%s room %s" % (r.get("level"), r.get("number")) for i, r in no_hours) if no_hours else "")
    # the object pass (program/objects.json, program/affordances.json): added objects whose position is inferred,
    # activities whose parameters are still pending, and kinds in the catalogue filled from general use
    objects_path = os.path.join(PROGRAM, "objects.json")
    objects = json.load(open(objects_path, encoding="utf-8")).get("objects", []) if os.path.exists(objects_path) else []
    aff_path = os.path.join(PROGRAM, "affordances.json")
    kinds = json.load(open(aff_path, encoding="utf-8")).get("kinds", {}) if os.path.exists(aff_path) else {}
    pending_acts = [(i, r, a) for i, r in items for a in r.get("activities", []) if a.get("pending")]
    with_objects = sorted({(r.get("level"), r.get("number")) for i, r in items if r.get("objects")})
    out += ["", "## Objects and activities", ""]
    out.append("%d rooms have been through the object pass (%s); %d added objects, %d of them placed by rule (position inferred); %d activities await their parameters; %d catalogue kinds are filled from general use and to be confirmed." % (
        len(with_objects), ", ".join("%s room %s" % lr for lr in with_objects) or "none", len(objects),
        sum(1 for o in objects if o.get("inferred_position")), len(pending_acts), sum(1 for k in kinds.values() if k.get("inferred"))))
    for o in objects:
        if o.get("inferred_position"):
            out.append("- [ ] %s, room %s: %s %s, position inferred: %s" % (o.get("level"), o.get("room_number"), o.get("id"), o.get("kind"), o.get("inferred_note") or ""))
    for i, r, a in pending_acts:
        out.append("- [ ] %s, room %s: activity %s: %s" % (r.get("level"), r.get("number"), a.get("kind"), a.get("pending")))
    rekinds = json.load(open(objects_path, encoding="utf-8")).get("rekind", {}) if os.path.exists(objects_path) else {}
    for eid, rk in rekinds.items():
        if rk.get("kind_inferred"):
            out.append("- [ ] element %s taken as %s (kind inferred): %s" % (eid, rk.get("kind"), rk.get("reason")))
    if kinds:
        out.append("- [ ] catalogue kinds to confirm: %s" % ", ".join(k for k, v in kinds.items() if v.get("inferred")))
    out += ["", "## Summary by level", ""]
    by_level = defaultdict(Counter)
    for i, r in items:
        by_level[r.get("level")][r.get("use") or ("flagged" if r.get("status") == "flagged" else "?")] += 1
    for lv in LEVEL_ORDER + [l for l in by_level if l not in LEVEL_ORDER]:
        if lv in by_level:
            out.append("- %s: %s" % (lv, ", ".join("%d %s" % (n, u) for u, n in sorted(by_level[lv].items(), key=lambda kv: -kv[1]))))
    out.append("")
    with open(os.path.join(PROGRAM, "TODO.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
